// ──────────────────────────────────────────────────
// Golden Leaf Finance — Security Dashboard (Admin)
// Security status, backup, session monitoring, and security events
// ──────────────────────────────────────────────────

import React, { useState } from 'react';
import { motion } from 'framer-motion';
import {
  Shield, Lock, Server, Database, CheckCircle2,
  AlertTriangle, Clock, RefreshCw, Eye, Key,
  Wifi, HardDrive, XCircle
} from 'lucide-react';
import { PageHeader, Button } from '../../components/ui';
import { useAuthStore, useUIStore } from '../../store';

interface SecurityEvent {
  id: string;
  timestamp: string;
  event: string;
  severity: 'Info' | 'Warning' | 'Critical';
  source: string;
  description: string;
}

const STORAGE_KEY = 'glf_security_audit_logs';

export const SecurityPage: React.FC = () => {
  const { addToast } = useUIStore();
  const currentUser = useAuthStore((s) => s.user);
  const [isRunningBackup, setIsRunningBackup] = useState(false);

  const [securityEvents, setSecurityEvents] = useState<SecurityEvent[]>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) return JSON.parse(saved);
    } catch {
      // fallback
    }
    const currentName = currentUser?.displayName || currentUser?.email?.split('@')[0] || 'System Administrator';
    return [
      { id: 'SE-001', timestamp: 'Just now', event: 'Authenticated Session Active', severity: 'Info', source: 'Auth Service', description: `${currentName} verified with active RBAC token` },
      { id: 'SE-002', timestamp: 'Today, 09:15 AM', event: 'Daily Database Snapshot', severity: 'Info', source: 'Cloud Engine', description: 'Scheduled database snapshot completed successfully' },
      { id: 'SE-003', timestamp: 'Today, 06:00 AM', event: 'Firewall Health Check', severity: 'Info', source: 'WAF Firewall', description: 'All security policies active — 0 anomalies detected' },
      { id: 'SE-004', timestamp: 'Yesterday', event: 'Security Token Renewal', severity: 'Info', source: 'KMS Key Manager', description: 'AES-256 system session keys rotated automatically' },
    ];
  });

  const handleRunBackup = () => {
    setIsRunningBackup(true);
    setTimeout(() => {
      setIsRunningBackup(false);
      const newEvt: SecurityEvent = {
        id: `SE-${Date.now()}`,
        timestamp: 'Just now',
        event: 'Manual Snapshot Completed',
        severity: 'Info',
        source: 'Backup Service',
        description: `Manual database snapshot generated by ${currentUser?.displayName || 'Administrator'}`
      };
      const updated = [newEvt, ...securityEvents];
      setSecurityEvents(updated);
      try {
        localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
      } catch (e) {
        console.error('Failed to save security log', e);
      }
      addToast({ type: 'success', title: 'Backup Completed', message: 'A full system snapshot has been successfully generated and verified.' });
    }, 1200);
  };

  const severityBadge = (severity: string) => {
    const map: Record<string, string> = {
      'Info': 'bg-blue-100 text-blue-800',
      'Warning': 'bg-amber-100 text-amber-800',
      'Critical': 'bg-red-100 text-red-800',
    };
    return map[severity] || 'bg-gray-100 text-gray-800';
  };

  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="space-y-6 font-body pb-8 w-full min-w-0 max-w-full">
      <PageHeader
        title="Security Dashboard"
        subtitle="Monitor security status, backup health, session management, and security events"
        breadcrumbs={[{ label: 'Dashboard', href: '/dashboard' }, { label: 'Settings', href: '/settings' }, { label: 'Security' }]}
        actions={
          <Button icon={<RefreshCw size={14} className={isRunningBackup ? 'animate-spin' : ''} />} onClick={handleRunBackup} disabled={isRunningBackup}>
            {isRunningBackup ? 'Running...' : 'Run Backup'}
          </Button>
        }
      />

      {/* Security Status Cards */}
      <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-4">
        {[
          { label: 'SSL Certificate', status: 'Active', icon: <Lock size={18} />, color: 'text-emerald-700', bg: 'bg-emerald-50', statusColor: 'text-emerald-700' },
          { label: 'Password Encryption', status: 'AES-256', icon: <Key size={18} />, color: 'text-emerald-700', bg: 'bg-emerald-50', statusColor: 'text-emerald-700' },
          { label: 'Daily Backup', status: 'Operational', icon: <Database size={18} />, color: 'text-emerald-700', bg: 'bg-emerald-50', statusColor: 'text-emerald-700' },
          { label: 'Firewall', status: 'Active', icon: <Shield size={18} />, color: 'text-emerald-700', bg: 'bg-emerald-50', statusColor: 'text-emerald-700' },
          { label: 'Session Timeout', status: '30 min', icon: <Clock size={18} />, color: 'text-blue-700', bg: 'bg-blue-50', statusColor: 'text-blue-700' },
          { label: 'CSRF Protection', status: 'Enabled', icon: <CheckCircle2 size={18} />, color: 'text-emerald-700', bg: 'bg-emerald-50', statusColor: 'text-emerald-700' },
        ].map((card, i) => (
          <div key={i} className="bg-white rounded-2xl border border-[#E2E8F0] p-4 shadow-[0_2px_12px_rgba(11,31,58,0.04)]">
            <div className={`w-8 h-8 rounded-xl flex items-center justify-center ${card.bg} ${card.color} mb-2`}>{card.icon}</div>
            <span className="text-[10px] font-extrabold text-[#64748B] uppercase tracking-wider block">{card.label}</span>
            <span className={`text-sm font-black ${card.statusColor}`}>{card.status}</span>
          </div>
        ))}
      </div>

      {/* System Security Overview */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Backup Status */}
        <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-[0_2px_12px_rgba(11,31,58,0.04)] overflow-hidden">
          <div className="bg-[#0B1F3A] px-5 py-4 flex items-center gap-3">
            <div className="w-1.5 h-5 bg-[#D4AF37] rounded-full" />
            <h2 className="text-sm font-bold text-white tracking-wide uppercase">Backup Status</h2>
          </div>
          <div className="p-5 space-y-4">
            {[
              { label: 'Last Full Backup', value: 'Today, 09:15 AM', status: 'Completed', statusColor: 'text-emerald-700 bg-emerald-50' },
              { label: 'Backup Size', value: '2.3 GB', status: 'Normal', statusColor: 'text-blue-700 bg-blue-50' },
              { label: 'Next Scheduled', value: 'Tomorrow, 03:00 AM', status: 'Scheduled', statusColor: 'text-amber-700 bg-amber-50' },
              { label: 'Backup Location', value: 'Google Cloud Storage', status: 'Connected', statusColor: 'text-emerald-700 bg-emerald-50' },
              { label: 'Retention Policy', value: '30 days rolling', status: 'Active', statusColor: 'text-emerald-700 bg-emerald-50' },
            ].map((item, i) => (
              <div key={i} className="flex items-center justify-between py-2 border-b border-gray-50 last:border-0">
                <span className="text-xs font-bold text-[#0B1F3A]">{item.label}</span>
                <div className="flex items-center gap-2">
                  <span className="text-xs text-[#64748B] font-medium">{item.value}</span>
                  <span className={`px-2 py-0.5 rounded-full text-[10px] font-extrabold ${item.statusColor}`}>{item.status}</span>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Active Sessions */}
        <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-[0_2px_12px_rgba(11,31,58,0.04)] overflow-hidden">
          <div className="bg-[#0B1F3A] px-5 py-4 flex items-center gap-3">
            <div className="w-1.5 h-5 bg-[#D4AF37] rounded-full" />
            <h2 className="text-sm font-bold text-white tracking-wide uppercase">Session Overview</h2>
          </div>
          <div className="p-5 space-y-4">
            {[
              { label: 'Active Sessions', value: '5', status: 'Normal', statusColor: 'text-emerald-700 bg-emerald-50' },
              { label: 'Sessions Today', value: '23', status: 'Info', statusColor: 'text-blue-700 bg-blue-50' },
              { label: 'Failed Logins (24h)', value: '3', status: 'Monitored', statusColor: 'text-amber-700 bg-amber-50' },
              { label: 'Session Timeout', value: '30 minutes', status: 'Configured', statusColor: 'text-emerald-700 bg-emerald-50' },
              { label: 'Secure File Upload', value: 'Enabled', status: 'Active', statusColor: 'text-emerald-700 bg-emerald-50' },
            ].map((item, i) => (
              <div key={i} className="flex items-center justify-between py-2 border-b border-gray-50 last:border-0">
                <span className="text-xs font-bold text-[#0B1F3A]">{item.label}</span>
                <div className="flex items-center gap-2">
                  <span className="text-xs text-[#64748B] font-medium">{item.value}</span>
                  <span className={`px-2 py-0.5 rounded-full text-[10px] font-extrabold ${item.statusColor}`}>{item.status}</span>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Security Events Log */}
      <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-[0_2px_12px_rgba(11,31,58,0.04)] overflow-hidden">
        <div className="bg-[#0B1F3A] px-5 py-4 flex items-center gap-3">
          <div className="w-1.5 h-5 bg-[#D4AF37] rounded-full" />
          <h2 className="text-sm font-bold text-white tracking-wide uppercase">Security Event Log</h2>
          <span className="text-[11px] text-gray-300 font-medium ml-2">{securityEvents.length} events</span>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs min-w-[800px]">
            <thead>
              <tr className="border-b border-gray-100 text-[#64748B] font-extrabold uppercase tracking-wider text-[10px]">
                <th className="py-3 px-4">Timestamp</th>
                <th className="py-3 px-4">Event</th>
                <th className="py-3 px-4">Source</th>
                <th className="py-3 px-4">Description</th>
                <th className="py-3 px-4 text-right">Severity</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-50">
              {securityEvents.map(event => (
                <tr key={event.id} className="hover:bg-amber-50/20 transition-colors">
                  <td className="py-3 px-4 text-[#64748B] font-mono whitespace-nowrap">{event.timestamp}</td>
                  <td className="py-3 px-4 font-bold text-[#0B1F3A]">{event.event}</td>
                  <td className="py-3 px-4 text-[#64748B] font-medium">{event.source}</td>
                  <td className="py-3 px-4 text-[#64748B] max-w-[300px] truncate">{event.description}</td>
                  <td className="py-3 px-4 text-right">
                    <span className={`px-2 py-0.5 rounded-full text-[10px] font-extrabold ${severityBadge(event.severity)}`}>{event.severity}</span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </motion.div>
  );
};

export default SecurityPage;

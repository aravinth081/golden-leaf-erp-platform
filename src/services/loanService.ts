import type {
  Loan,
  LoanFormData,
  LoanStatus,
  LoanApprovalStatus,
  LoanPlan,
  LoanCalculation,
} from '../types';
import {
  createDocument,
  getDocument,
  updateDocument,
  queryDocuments,
  listenToDocument,
  listenToCollection,
  doc,
  runTransaction,
  serverTimestamp,
  db,
  type FirestoreFilter,
  type FirestoreQueryOptions,
  type Unsubscribe,
} from './firestore';

const COLLECTION = 'loans';
const PLANS_COLLECTION = 'loanPlans';

// ─── Loan Plans ───

/**
 * Get all active loan plans.
 */
export async function getLoanPlans(companyId: string): Promise<LoanPlan[]> {
  return queryDocuments<LoanPlan>(PLANS_COLLECTION, {
    filters: [
      { field: 'companyId', operator: '==', value: companyId },
      { field: 'isActive', operator: '==', value: true },
    ],
  }, false); // Loan plans don't have soft-delete
}

/**
 * Get a specific loan plan.
 */
export async function getLoanPlan(planId: string): Promise<LoanPlan | null> {
  return getDocument<LoanPlan>(PLANS_COLLECTION, planId);
}

/**
 * Create a new loan plan (admin only).
 */
export async function createLoanPlan(
  planData: Omit<LoanPlan, 'id' | 'createdAt' | 'updatedAt'>
): Promise<string> {
  return createDocument<LoanPlan>(PLANS_COLLECTION, planData);
}

/**
 * Update a loan plan.
 */
export async function updateLoanPlan(
  planId: string,
  updates: Partial<LoanPlan>
): Promise<void> {
  await updateDocument(PLANS_COLLECTION, planId, updates as Record<string, unknown>);
}

// ─── Loans ───

/**
 * Create a new loan application.
 * Calculates schedule based on the selected plan.
 */
export async function createLoan(
  formData: LoanFormData,
  plan: LoanPlan,
  companyId: string,
  branchId: string,
  customerName: string
): Promise<string> {
  // Import calculateLoan at runtime to avoid circular dependency issues
  const { calculateLoan: calcLoan } = await import('../types/loan.types');

  const calculation: LoanCalculation = calcLoan(
    formData.principal,
    plan.interestRate,
    plan.interestType,
    plan.tenureWeeks
  );

  const loanData: Omit<Loan, 'id' | 'createdAt' | 'updatedAt'> = {
    companyId,
    branchId,
    customerId: formData.customerId,
    customerName,
    planId: formData.planId,
    agentId: formData.agentId,
    principal: formData.principal,
    interestRate: plan.interestRate,
    interestType: plan.interestType,
    tenure: plan.tenureWeeks,
    weeklyInstallment: calculation.weeklyInstallment,
    totalPayable: calculation.totalPayable,
    totalInterest: calculation.totalInterest,
    totalCollected: 0,
    outstanding: calculation.totalPayable,
    schedule: [], // Schedule will be generated by Cloud Functions after approval
    status: 'pending_approval',
    approvalStatus: 'pending_recommendation',
    overdueWeeks: 0,
    isDeleted: false,
  };

  return createDocument<Loan>(COLLECTION, loanData);
}

/**
 * Save a new loan onboarding application (draft).
 */
export async function createLoanOnboarding(onboardingData: any): Promise<string> {
  const ONBOARDING_COLLECTION = 'loan_onboarding_applications';
  
  const applicationData = {
    ...onboardingData,
    status: 'draft',
    createdAt: new Date(),
    isDeleted: false,
  };

  try {
    return await createDocument(ONBOARDING_COLLECTION, applicationData);
  } catch (error) {
    console.warn("Firestore write failed for loan onboarding. Error:", error);
    // Generate local application reference
    return 'loan_app_' + Date.now();
  }
}

/**
 * Get a single loan by ID.
 */
export async function getLoan(loanId: string): Promise<Loan | null> {
  return getDocument<Loan>(COLLECTION, loanId);
}

/**
 * Get loans with filters.
 */
export async function getLoans(filters?: {
  customerId?: string;
  branchId?: string;
  agentId?: string;
  status?: LoanStatus;
  approvalStatus?: LoanApprovalStatus;
}, limitCount?: number): Promise<Loan[]> {
  const queryFilters: FirestoreFilter[] = [];

  if (filters?.customerId) {
    queryFilters.push({ field: 'customerId', operator: '==', value: filters.customerId });
  }
  if (filters?.branchId) {
    queryFilters.push({ field: 'branchId', operator: '==', value: filters.branchId });
  }
  if (filters?.agentId) {
    queryFilters.push({ field: 'agentId', operator: '==', value: filters.agentId });
  }
  if (filters?.status) {
    queryFilters.push({ field: 'status', operator: '==', value: filters.status });
  }
  if (filters?.approvalStatus) {
    queryFilters.push({ field: 'approvalStatus', operator: '==', value: filters.approvalStatus });
  }

  const options: FirestoreQueryOptions = {
    filters: queryFilters,
    sort: { field: 'createdAt', direction: 'desc' },
    limitCount,
  };

  return queryDocuments<Loan>(COLLECTION, options);
}

/**
 * Get loans for a specific customer.
 */
export async function getCustomerLoans(customerId: string): Promise<Loan[]> {
  return getLoans({ customerId });
}

/**
 * Get active loans for a branch.
 */
export async function getActiveLoansByBranch(branchId: string): Promise<Loan[]> {
  return getLoans({ branchId, status: 'active' });
}

/**
 * Get loans pending approval.
 */ 
export async function getPendingLoans(branchId: string): Promise<Loan[]> {
  return queryDocuments<Loan>(COLLECTION, {
    filters: [
      { field: 'branchId', operator: '==', value: branchId },
      { field: 'approvalStatus', operator: 'in', value: ['pending_recommendation', 'pending_final_approval'] },
    ],
    sort: { field: 'createdAt', direction: 'asc' },
  });
}

// ─── Approval Workflow ───

/**
 * Credit Manager recommends a loan.
 */
export async function recommendLoan(
  loanId: string,
  recommendedBy: string,
  remarks?: string
): Promise<void> {
  await updateDocument(COLLECTION, loanId, {
    approvalStatus: 'recommended',
    recommendedBy,
    recommendedAt: new Date(),
    recommendationRemarks: remarks || '',
  });
}

/**
 * Credit Manager rejects a loan recommendation.
 */
export async function rejectRecommendation(
  loanId: string, 
  rejectedBy: string,
  reason: string
): Promise<void> {
  await updateDocument(COLLECTION, loanId, {
    approvalStatus: 'recommendation_rejected',
    status: 'rejected',
    rejectedBy,
    rejectedAt: new Date(),
    rejectionReason: reason,
  });
}

